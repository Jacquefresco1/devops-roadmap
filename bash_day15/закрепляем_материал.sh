# Day 15 — Закреп

* `check_files` может быть полностью универсальной: конкретный шаблон передаётся через аргументы функции, а не зашивается внутрь.
* `$1` функции — первый аргумент функции, `$2` — второй.
* Конкретный шаблон можно передавать при вызове:
  `check_files "$1" "*.log"`
* Скрипт и функция могут иметь разное количество аргументов: скрипт может получить 2 аргумента, а функция использовать их как свои `$1` и `$2`.
* При нескольких вызовах одной функции результат последнего вызова остаётся в общей переменной, поэтому предыдущий результат нужно сохранить, если он ещё понадобится.
* Для трёх проверок можно использовать отдельные переменные результатов и статусов.
* Агрегация статусов:
  `2 > 1 > 0`

  * `2` → ошибка
  * `1` → внимание
  * `0` → всё OK
* `for` повторяет один и тот же блок кода для нескольких значений.
* `"$@"` содержит все аргументы скрипта отдельно.
* `for item in "$@"; do ... done` последовательно передаёт каждый аргумент в переменную `item`.
* Имя переменной цикла можно выбрать самостоятельно.
* `case` выбирает ветку для значения, `for` повторяет один блок для нескольких значений.
* Следующий шаг: объединить `for "$@"` с универсальной функцией `check_files`.
