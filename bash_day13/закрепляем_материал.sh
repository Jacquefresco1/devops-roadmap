Ключевой принцип Day 13

Результат команды и её exit status — две разные вещи.

find может:

вернуть 0, потому что команда выполнилась успешно;
при этом вернуть пустой результат, потому что ничего не найдено.

Поэтому:

$? → как выполнилась команда
переменная → что команда вернула в stdout
Ещё один важный принцип

Функция может выступать как проверка/датчик состояния:

return 0 → состояние A
return 1 → состояние B
return 2 → ошибка

А код снаружи интерпретирует эти состояния.

