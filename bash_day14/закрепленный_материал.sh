DAY 14 — Bash Functions / Independent Checks / Status Aggregation

Сегодня:

- Разбили проверки системы на независимые функции.
- Каждая функция выполняет свою отдельную проверку.
- Каждая функция возвращает статус через return.
- Использовали единую систему статусов:
  0 — OK
  1 — ATTENTION
  2 — ERROR

- Все независимые проверки выполняются независимо друг от друга.
- Результаты каждой проверки сохраняются в main.
- Научились разделять:
  return → статус функции
  переменная → данные функции

- Использовали find для поиска файлов.
- Поняли важное отличие:
  find может завершиться с кодом 0, даже если ничего не нашёл.
  Поэтому наличие результата проверяем отдельно через [ -n "$files" ].

- Научились передавать вывод одной команды другой через pipe:
  echo "$files" | wc -l

- Научились считать количество найденных файлов и сохранять результат:
  numbers=$(echo "$files" | wc -l)

- Разобрались со scope:
  local → переменная только внутри функции.
  Если значение нужно после завершения функции, переменная не должна быть local.

