13. Что реально закреплено

$# → количество аргументов
$1 / $2 → значения аргументов
case → выбор команды
if / elif / else → логика
-f / -d / -e → проверки объектов
$? → exit status предыдущей команды
result="$?" → сохранение exit status
-eq / -ne → числовое сравнение
= / != → сравнение строк
exit 0 / exit 1 → успешное/ошибочное завершение скрипта
;; → завершение ветки case
fi → завершение if
esac → завершение case

Главный принцип Day 10:

Команда → exit status → сохранить при необходимости → обработать результат.
