DAY 10 — EXIT STATUS И ОБРАБОТКА РЕЗУЛЬТАТА КОМАНД

1. Что такое exit status

После выполнения команды Bash получает её exit status.

0 → успех.
Не 0 → команда завершилась неуспешно.

$? - показывает exit status непосредственно предыдущей команды.

2. Главная ловушка с $?

$? - не хранит историю команд. Он всегда показывает результат только последней выполненной команды.

Пример:

ls "$1"
echo "Hello"

После echo: $? → результат echo

Результат ls больше недоступен через $?.

3. Как сохранить результат

Сразу после команды:

ls "$1"
result="$?"

Теперь: result → сохранённый exit status ls.

Даже если после этого выполнить:

echo "Hello"
echo "Something else"

значение result не изменится.

4. Практическая схема

command
↓
$?
↓
result="$?"
↓
другие команды
↓
if проверяет result

5. Проверка сохранённого результата

if [ "$result" -eq 0 ]; then
	echo "Command succeeded"
else
	echo "Command failed"
	exit 1
fi

Здесь if смотрит на значение переменной result, а не на текущий $?.

6. Различие между $? и result

$? → текущий exit status последней команды.

result → сохранённое значение exit status.

Например:

ls "$1"
result="$?"

echo "Hello"

После echo:

$? = 0
result = результат ls

Это и есть главная причина сохранять $?.

7. Несколько exit status

Можно проверять конкретные значения:

if [ "$result" -eq 0 ]; then
	...
elif [ "$result" -eq 2 ]; then
	...
else
	...
fi

Например:

0 → команда успешна
2 → конкретный известный вариант ошибки
другое значение → другой вариант ошибки

8. exit и $? — не одно и то же

$? показывает, какой exit status уже вернула предыдущая команда.

exit устанавливает exit status самого скрипта и немедленно завершает его.

Например:

echo "Failed"
exit 1

echo успешно выполнится, но exit 1 завершит весь скрипт с кодом 1.

9. Не каждый успешный результат требует exit 0

Если скрипт дошёл до конца после успешной команды:

echo "Success"

последняя команда обычно возвращает 0, поэтому скрипт завершится успешно.

Явный exit 0 нужен, когда мы хотим явно указать успешное завершение или завершить скрипт раньше.

10. if может проверять exit status команды напрямую

Вместо:

ls "$1"
result="$?"

if [ "$result" -eq 0 ]; then
	...
fi

можно:

if ls "$1"; then
	...
else
	...
fi

В этом случае if автоматически использует exit status ls.

11. Когда сохранять результат, а когда проверять напрямую

Если результат нужен только для одного решения:

if command; then
	...
fi

Если результат нужно:

— сохранить;
— вывести;
— использовать несколько раз;
— сравнить с несколькими значениями;

тогда:

command
result="$?"

