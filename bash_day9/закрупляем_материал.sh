DAY 9 — Закрепление

1. $#

$# - показывает количество аргументов, переданных скрипту.

Количество аргументов не зависит от того, используются ли они в коде.

bash day9.sh hello world Linux DevOps

$# = 4

2. $1 и $#

Важно не путать:

$1 → значение первого аргумента.
$# → количество всех аргументов.

bash day9.sh Linux DevOps

$1 = Linux
$2 = DevOps
$# = 2

3. Кавычки в аргументах

bash day9.sh “hello world” Linux

Здесь передано 2 аргумента:

$1 = hello world
$2 = Linux
$# = 2

Кавычки позволяют сохранить hello world одним аргументом.

4. Проверка количества аргументов

if [ "$#" -ne 1 ]; then
	echo "Error: needs exactly 1 argument"
	exit 1
fi

Если количество аргументов не равно 1, скрипт завершается.

5. Проверка конкретного аргумента

if [ "$1" != "check" ]; then
	echo “Unknown command”
	exit 1
fi

Здесь проверяется не количество аргументов, а значение первого аргумента.

6. Важное различие операторов

Числа:

-eq → равно
-ne → не равно

Строки:

= → равно
!= → не равно

Например:

[ "$#" -eq 2 ]

проверяет число.

[ "$1" = "check" ]

проверяет строку.

7. Проверка аргумента как файла

После проверки количества аргументов:

if [ "$#" -ne 2 ]; then
	exit 1
fi

можно использовать:

[ -f "$2" ]

для проверки второго аргумента как обычного файла.

8. Необязательно использовать новый синтаксис ${!#}

Если известно, что передан ровно один аргумент:

$# = 1

то этот аргумент автоматически находится в:

$1

Поэтому:

[ "$#" -eq 1 ] && [ -f "$1" ]

достаточно для проверки количества аргументов и первого аргумента как файла.

9. if внутри case

Проверка, относящаяся только к конкретной команде, должна находиться внутри соответствующей ветки case.

case "$1" in
	check)
		if [ -f "$2" ]; then
			echo "File exists: $2"
		else
			echo "File does not exist: $2"
			exit 1
		fi
	;;
esac

10. exit 0 не всегда нужен

Если последняя команда скрипта успешно выполнилась, скрипт обычно завершится с её exit status.

Например:

echo “Success”

обычно завершает скрипт с status 0.

Явный exit 0 можно использовать, чтобы явно обозначить успешное завершение.

11. exit и ;; — разные вещи

exit 1 → немедленно завершает весь скрипт.

;; → завершает текущую ветку case и позволяет скрипту продолжить выполнение после case.

12. Ошибка в первой версии проверки check

Неправильная архитектура:

if [ "$#" -ne 2 ]; then
	…
elif [ -f "$2" ]; then
	…
fi

Проверка файла выполнялась до определения команды.

Например:

./day9.sh status test.txt

сначала проверялся test.txt, хотя команда status могла иметь совершенно другую логику.

Правильнее:

if [ "$#" -ne 2 ]; then
	…
	exit 1
fi

case "$1" in
	check)
		if [ -f "$2" ]; then
			…
		fi
	;;
	…
esac

Сначала определяется команда, затем выполняется логика именно этой команды.

13. Итоговая структура CLI

Проверка входных данных:

$#
↓
количество аргументов

$1
↓
какую команду запросили

$2
↓
над каким объектом работает команда

case
↓
выбор команды

if
↓
проверка условий конкретной команды

exit
↓
результат работы скрипта
